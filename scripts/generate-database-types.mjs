import { readFile, writeFile } from 'node:fs/promises'
import { createTestDatabase } from '../supabase/tests/database.mjs'

// Generates from the actual local migrations, never from a hosted project.
// Unsupported PostgreSQL types fail instead of silently weakening contracts.
const output = new URL('../lib/supabase/database.types.ts', import.meta.url)
function tsType(type) {
  if (type.startsWith('_')) return `${tsType(type.slice(1))}[]`
  if (['text', 'varchar', 'bpchar', 'uuid', 'timestamp', 'timestamptz', 'date', 'time'].includes(type)) return 'string'
  if (['int2', 'int4', 'int8', 'float4', 'float8', 'numeric'].includes(type)) return 'number'
  if (type === 'bool') return 'boolean'
  if (['json', 'jsonb'].includes(type)) return 'Json'
  if (type === 'void') return 'undefined'
  throw new Error(`Unsupported database type: ${type}`)
}
const db = await createTestDatabase()
try {
  const { rows: columns } = await db.query(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable,
      c.column_default, c.is_identity, c.is_generated
    from information_schema.columns c
    join information_schema.tables t using (table_schema, table_name)
    where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
    order by c.table_name, c.ordinal_position
  `)
  const { rows: relations } = await db.query(`
    select src.relname as table_name, con.conname as name,
      array(select a.attname from unnest(con.conkey) with ordinality k(n, ord)
        join pg_attribute a on a.attrelid=con.conrelid and a.attnum=k.n order by k.ord) as columns,
      dst.relname as target,
      array(select a.attname from unnest(con.confkey) with ordinality k(n, ord)
        join pg_attribute a on a.attrelid=con.confrelid and a.attnum=k.n order by k.ord) as target_columns,
      exists(select 1 from pg_constraint u where u.conrelid=con.conrelid
        and u.contype in ('p','u') and u.conkey=con.conkey) as one_to_one
    from pg_constraint con
    join pg_class src on src.oid=con.conrelid join pg_namespace sn on sn.oid=src.relnamespace
    join pg_class dst on dst.oid=con.confrelid join pg_namespace dn on dn.oid=dst.relnamespace
    where con.contype='f' and sn.nspname='public' and dn.nspname='public'
    order by src.relname, con.conname
  `)
  const { rows: functions } = await db.query(`
    select p.proname as name, p.pronargdefaults as defaults, p.proretset as returns_set,
      t.typname as return_type,
      coalesce((select json_agg(json_build_object('name', p.proargnames[k.ord],
        'mode', coalesce(p.proargmodes[k.ord], 'i'), 'type', at.typname) order by k.ord)
        from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) with ordinality k(oid, ord)
        join pg_type at on at.oid=k.oid), '[]'::json) as args
    from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type t on t.oid=p.prorettype
    where n.nspname='public' and t.typname <> 'trigger'
    order by p.proname
  `)
  const lines = [
    '// Generated by node scripts/generate-database-types.mjs from repository migrations.',
    '// Does not certify the deployed Supabase schema. Do not edit by hand.',
    'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]',
    '', 'export type Database = {', '  public: {', '    Tables: {',
  ]
  for (const table of [...new Set(columns.map(c => c.table_name))]) {
    lines.push(`      ${table}: {`)
    for (const mode of ['Row', 'Insert', 'Update']) {
      lines.push(`        ${mode}: {`)
      for (const c of columns.filter(c => c.table_name === table)) {
        const generated = c.is_generated !== 'NEVER'
        const optional = mode === 'Update' || (mode === 'Insert' && (c.is_nullable === 'YES' || c.column_default !== null || c.is_identity === 'YES' || generated))
        const type = generated && mode !== 'Row' ? 'never' : tsType(c.udt_name) + (c.is_nullable === 'YES' ? ' | null' : '')
        lines.push(`          ${c.column_name}${optional ? '?' : ''}: ${type}`)
      }
      lines.push('        }')
    }
    lines.push('        Relationships: [')
    for (const r of relations.filter(r => r.table_name === table)) {
      lines.push(`          { foreignKeyName: ${JSON.stringify(r.name)}; columns: ${JSON.stringify(r.columns)}; isOneToOne: ${r.one_to_one}; referencedRelation: ${JSON.stringify(r.target)}; referencedColumns: ${JSON.stringify(r.target_columns)} },`)
    }
    lines.push('        ]', '      }')
  }
  lines.push('    }', '    Views: { [_ in never]: never }', '    Functions: {')
  for (const f of functions) {
    const inputs = f.args.filter(a => ['i', 'b', 'v'].includes(a.mode))
    const outputs = f.args.filter(a => ['o', 'b', 't'].includes(a.mode))
    lines.push(`      ${f.name}: {`, '        Args: {')
    for (const [i, a] of inputs.entries()) {
      if (!a.name) throw new Error(`Unnamed RPC argument: ${f.name}`)
      lines.push(`          ${a.name}${i >= inputs.length - f.defaults ? '?' : ''}: ${tsType(a.type)} | null`)
    }
    lines.push('        }')
    const result = outputs.length ? `{ ${outputs.map(a => `${a.name}: ${tsType(a.type)}`).join('; ')} }` : tsType(f.return_type)
    lines.push(`        Returns: ${result}${f.returns_set ? '[]' : ''}`, '      }')
  }
  lines.push('    }', '    Enums: { [_ in never]: never }', '    CompositeTypes: { [_ in never]: never }', '  }', '}', '',
    "export type TableName = keyof Database['public']['Tables']",
    "export type Tables<Name extends TableName> = Database['public']['Tables'][Name]['Row']",
    "export type TablesInsert<Name extends TableName> = Database['public']['Tables'][Name]['Insert']",
    "export type TablesUpdate<Name extends TableName> = Database['public']['Tables'][Name]['Update']", '')
  const source = lines.join('\n')
  if (process.argv.includes('--check')) {
    if ((await readFile(output, 'utf8')) !== source) throw new Error('Database types are stale; regenerate them.')
    console.log('Database type contracts match repository migrations.')
  } else {
    await writeFile(output, source)
    console.log('Generated lib/supabase/database.types.ts')
  }
} finally {
  await db.close()
}