import { randomUUID } from 'node:crypto'
import type { createClient } from '@/lib/supabase/server'
import { assertMediaUpload, isOwnedMediaPath } from './upload-validation'
import { isValidMediaUrl } from './is-valid-media-url'

export type MediaClient = Awaited<ReturnType<typeof createClient>>
export type MediaInput = { file: File | null; path: string; folder: string; kind: 'image' | 'video'; maxBytes: number; optional?: boolean }
export class MediaMutationError extends Error {}
export function fileField(form: FormData, key: string): File | null {
  const value = form.get(key)
  return value instanceof File && value.name ? value : null
}
export function mutationId(form: FormData): string {
  const value = String(form.get('mutation_id') || '').trim()
  if (!value) return randomUUID()
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)) throw new MediaMutationError('Invalid publication request. Reload and try again.')
  return value
}
const imageTypes = new Set(['image/jpeg','image/jpg','image/png','image/webp','image/gif'])
const videoTypes = new Set(['video/mp4','video/webm','video/quicktime','video/x-m4v','video/3gpp','video/3gpp2','video/ogg'])
function acceptedType(kind: 'image' | 'video', type: string) {
  return (kind === 'image' ? imageTypes : videoTypes).has(type.toLowerCase().split(';')[0].trim())
}
/** Validate every input before starting any upload. */
export async function validateMedia(input: MediaInput, owner: string) {
  if (input.file) {
    if (!acceptedType(input.kind, input.file.type) || input.file.size > input.maxBytes) throw new MediaMutationError('The selected media type or size is not supported.')
    try { await assertMediaUpload(input.file) } catch { throw new MediaMutationError('The selected file does not match a supported media format.') }
  } else if (!input.path) {
    if (!input.optional) throw new MediaMutationError('Select a media file or enter a valid public media URL.')
  } else if (!isOwnedMediaPath(input.path, owner) && !isValidMediaUrl(input.path)) {
    throw new MediaMutationError('The media reference is invalid or belongs to another account.')
  }
}
export async function resolveMedia(client: MediaClient, owner: string, input: MediaInput, fresh: string[]): Promise<string | null> {
  if (input.file) {
    const extension = input.file.name.split('.').pop()!.toLowerCase()
    const path = `${input.folder}/${owner}/${randomUUID()}.${extension}`
    // Retain the attempted path even if the upload response is lost. It has not
    // been submitted to a DB mutation and was generated by this request only.
    fresh.push(path)
    const { error } = await client.storage.from('media').upload(path, input.file, { contentType: input.file.type, upsert: false, cacheControl: '3600' })
    if (error) throw new MediaMutationError('Upload failed. Try again when your connection is stable.')
    return path
  }
  if (!input.path) return null
  if (isOwnedMediaPath(input.path, owner)) {
    // The user's authenticated Storage SELECT policy checks ownership. Never
    // trust client-supplied MIME/size/path claims for a direct upload.
    const { data, error } = await client.storage.from('media').info(input.path)
    if (error || !data || typeof data.size !== 'number' || data.size <= 0 || data.size > input.maxBytes || !acceptedType(input.kind, data.contentType || '')) {
      throw new MediaMutationError('The uploaded media could not be verified. Upload it again.')
    }
  }
  return input.path
}
/** Only call for this request's fresh uploads and a known non-committed write. */
export async function cleanupFreshUploads(client: MediaClient, owner: string, fresh: readonly string[]): Promise<boolean> {
  const paths = [...new Set(fresh)]
  if (!paths.length) return true
  if (paths.some(path => !isOwnedMediaPath(path, owner))) return false
  try { return !(await client.storage.from('media').remove(paths)).error } catch { return false }
}
export function knownDatabaseRejection(error: { code?: string } | null): boolean {
  // Transport/timeout/unknown failures can follow a committed transaction.
  // Never remove media on those outcomes.
  return !!error?.code && (/^(22|23)/.test(error.code) || ['42501','40001','P0001'].includes(error.code))
}
export function mediaFailure(error: unknown, fallback: string): string {
  return error instanceof MediaMutationError ? error.message : fallback
}
